package nebflow.core.pdf

import cats.effect.IO
import cats.effect.unsafe.implicits.global
import cats.syntax.all.*
import munit.CatsEffectSuite

import java.nio.charset.StandardCharsets
import scala.concurrent.duration.*

/**
 * PDF note/ask — the laziness / reuse / concurrency / failure contract.
 *
 * Every assertion here is about a fact a reviewer can re-derive from the file
 * system, not about an internal counter:
 *   · "open does not parse" is asserted as "the cache root has no entry";
 *   · "a second ask reuses the entry" as "meta.json's mtime and the manifest's
 *     generation time are unchanged";
 *   · "concurrent asks parse once" as "the parser subprocess ran exactly once"
 *     (counted by a wrapper interpreter that logs each spawn, and by the
 *     process-wide parse counter the HTTP concurrency spec also uses);
 *   · "a failure is readable and leaves nothing behind" as "Left(code) and no
 *     entry directory".
 *
 * Fixtures are generated by `scripts/tests/pdf_fixture.py` (real PDFs written by
 * an independent writer). The whole suite is skipped when `python3` or the
 * parser's dependencies (pdfplumber + pypdf) are unavailable, so a machine
 * without the parser never reports a false pass.
 */
class PdfFeatureSpec extends CatsEffectSuite:

  private val repoRoot = os.pwd
  private val fixtureScript = repoRoot / "scripts" / "tests" / "pdf_fixture.py"
  private val python = PdfParser.pythonBin()

  private def pythonReady: Boolean =
    os.exists(fixtureScript) &&
      scala.util
        .Try(os.proc(python, "-c", "import pdfplumber, pypdf").call(check = false).exitCode == 0)
        .getOrElse(false)

  private lazy val fixtureDir: os.Path =
    val dir = os.temp.dir(prefix = "pdf-fx-")
    os.proc(python, fixtureScript.toString, dir.toString).call(check = false)
    dir

  private lazy val simplePdf: os.Path = fixtureDir / "simple.pdf"

  private lazy val encryptedPdf: os.Path = fixtureDir / "encrypted.pdf"

  /** A data root per test: the cache path is derived from it, so isolation is real. */
  private def freshRoot(label: String): os.Path = os.temp.dir(prefix = s"pdf-root-$label-")

  /** Interpreter wrapper that records every spawn — the dedup evidence. */
  private def spawnCounter(dir: os.Path): (os.Path, os.Path) =
    val log = dir / "spawns.log"
    val wrapper = dir / "python-counting"
    os.write.over(
      wrapper,
      s"""#!/bin/sh
         |echo spawn >> ${log.toString}
         |exec $python "$$@"
         |""".stripMargin
    )
    os.perms.set(wrapper, "rwxr-xr-x")
    (wrapper, log)

  private def spawnCount(log: os.Path): Int =
    if !os.exists(log) then 0 else os.read(log).linesIterator.size

  test("open/lookup never parses: the cache root stays empty") {
    assume(pythonReady, "python3 + pdfplumber/pypdf are required for the PDF fixtures")
    val root = freshRoot("open")
    val cache = PdfCache.forDataRoot(root)
    for
      m <- cache.lookup("0" * 64)
      _ = assertEquals(m, None)
      count <- cache.entryCount
      _ = assertEquals(count, 0)
      // A note write must also stay parse-free, and must be readable back.
      w <- PdfNotes.put(root, "a" * 64, 3, "check this page", "verbatim snippet")
      _ = assert(w.isInstanceOf[PdfNotes.WriteResult.Ok], s"note write failed: $w")
      read <- PdfNotes.json(root, "a" * 64, 3, None)
      _ = assertEquals(read.hcursor.downField("page_verified").as[Boolean].toOption, Some(false))
      _ = assertEquals(read.hcursor.downField("note").downField("text").as[String].toOption, Some("check this page"))
      _ = assertEquals(
        read.hcursor.downField("note").downField("snippet").as[String].toOption,
        Some("verbatim snippet")
      )
      after <- cache.entryCount
      _ = assertEquals(after, 0, "writing a note must not create a cache entry")
      _ = assert(!os.exists(PdfCache.rootFor(root) / "00"), "no bucket directory may exist after open/note")
    yield ()
    end for
  }

  test("a note is keyed by document bytes, not by path, and conflicts are reported") {
    val root = freshRoot("note")
    val docA = "b" * 64
    val docB = "c" * 64
    for
      ok <- PdfNotes.put(root, docA, 1, "first")
      v1 = ok.asInstanceOf[PdfNotes.WriteResult.Ok].version
      // A stale conditional write writes NOTHING and reports the current version.
      stale <- PdfNotes.put(root, docA, 1, "overwrite", expectedVersion = Some(v1 - 1))
      _ = assertEquals(stale, PdfNotes.WriteResult.Conflict(v1))
      kept <- PdfNotes.get(root, docA, 1)
      _ = assertEquals(kept.flatMap(_.hcursor.downField("text").as[String].toOption), Some("first"))
      // Same page number, different document ⇒ a different note slot.
      otherDoc <- PdfNotes.get(root, docB, 1)
      _ = assertEquals(otherDoc, None)
      // Page 0 / bad digest are refused with a reason, never silently accepted.
      bad <- PdfNotes.put(root, docA, 0, "x")
      _ = assertEquals(bad, PdfNotes.WriteResult.BadPage(0))
      badSha <- PdfNotes.put(root, "not-a-digest", 1, "x")
      _ = assert(badSha.isInstanceOf[PdfNotes.WriteResult.BadDigest])
      // A note with a manifest in hand can be judged against the real page bound.
      manifest = PdfManifest(
        docA,
        "a.pdf",
        3,
        List("p0001.md", "p0002.md", "p0003.md"),
        PdfManifest.ParserId("pdfplumber", "0.11.10"),
        PdfParser.MarkdownVersion,
        1L,
        Nil,
        0,
        0
      )
      inRange <- PdfNotes.json(root, docA, 1, Some(manifest))
      _ = assertEquals(inRange.hcursor.downField("out_of_range").as[Boolean].toOption, Some(false))
      outOfRange <- PdfNotes.json(root, docA, 99, Some(manifest))
      _ = assertEquals(outOfRange.hcursor.downField("out_of_range").as[Boolean].toOption, Some(true))
    yield ()
    end for
  }

  test("ask parses once, publishes the documented layout, and a second ask reuses it") {
    assume(pythonReady, "python3 + pdfplumber/pypdf are required for the PDF fixtures")
    val root = freshRoot("ask")
    val cache = PdfCache.forDataRoot(root)
    val doc = simplePdf
    for
      first <- PdfAsk.ask(cache, root, doc, "simple.pdf", "what does page two say about r2c2?")
      json = first.toOption.getOrElse(fail(s"first ask failed: $first"))
      sha = json.hcursor.downField("manifest").downField("source_sha256").as[String].toOption.get
      pages = json.hcursor.downField("manifest").downField("page_count").as[Int].toOption
      _ = assertEquals(pages, Some(3))
      // Layout: the documented paths, exactly.
      entry = cache.entryDir(sha)
      _ = assert(os.exists(entry / "meta.json"), s"expected $entry/meta.json")
      _ = assert(os.exists(entry / "pages" / "p0001.md"), "expected pages/p0001.md")
      _ = assert(os.exists(entry / "media" / "p0003-0.png"), "expected media/p0003-0.png")
      _ = assert(
        os.exists(PdfCache.scriptDirFor(root)),
        "the parser script must be extracted lazily under the data root"
      )
      _ = assert(
        os.read(entry / "pages" / "p0003.md").contains("../media/p0003-0.png"),
        "page image links must be relative"
      )
      mtimeBefore = os.mtime(cache.metaPath(sha))
      generatedBefore = json.hcursor.downField("manifest").downField("generated_at_ms").as[Long].toOption
      countBefore <- cache.entryCount
      _ = assertEquals(countBefore, 1)
      // Reuse: same entry, no reparse.
      second <- PdfAsk.ask(cache, root, doc, "simple.pdf", "and page three?")
      json2 = second.toOption.getOrElse(fail(s"second ask failed: $second"))
      _ = assertEquals(
        json2.hcursor.downField("manifest").downField("generated_at_ms").as[Long].toOption,
        generatedBefore
      )
      _ = assertEquals(os.mtime(cache.metaPath(sha)), mtimeBefore)
      countAfter <- cache.entryCount
      _ = assertEquals(countAfter, 1)
    yield ()
    end for
  }

  test("concurrent asks for one document run the parser exactly once") {
    assume(pythonReady, "python3 + pdfplumber/pypdf are required for the PDF fixtures")
    val root = freshRoot("concurrent")
    val counterDir = os.temp.dir(prefix = "pdf-counter-")
    val (wrapper, log) = spawnCounter(counterDir)
    // Each ensure gets its OWN cache instance — the dedup under test is the
    // in-memory single-flight of one cache instance, which is what a gateway
    // process has. (Cross-process convergence is covered by the atomic publish.)
    val cache = new PdfCache(PdfCache.rootFor(root), PdfCache.scriptDirFor(root), wrapper.toString)
    val doc = simplePdf
    // Deterministic join exercise: start the owner, let it install the flight and
    // spawn the parser, THEN fire three more asks that must await that same parse
    // instead of starting their own.
    val run = for
      owner <- cache.ensure(doc, "simple.pdf").start
      _ <- IO.sleep(150.millis)
      joiners <- List.fill(3)(cache.ensure(doc, "simple.pdf")).parSequence
      first <- owner.joinWithNever
    yield first :: joiners
    for
      results <- run
      _ = assertEquals(
        results.flatMap(_.toOption).map(_.sourceSha256).distinct.size,
        1,
        s"expected one digest, got $results"
      )
      _ = assertEquals(results.count(_.isRight), 4, s"every concurrent caller must get the manifest: $results")
      spawns = spawnCount(log)
      _ = assertEquals(spawns, 1, s"the parser must run exactly once for concurrent asks (spawns=$spawns)")
      entries <- cache.entryCount
      _ = assertEquals(entries, 1)
    yield ()
  }

  test("failures are readable, leave no entry, and are retried instead of cached") {
    assume(pythonReady, "python3 + pdfplumber/pypdf are required for the PDF fixtures")
    val root = freshRoot("failure")
    val counterDir = os.temp.dir(prefix = "pdf-counter-fail-")
    val (wrapper, log) = spawnCounter(counterDir)
    val cache = new PdfCache(PdfCache.rootFor(root), PdfCache.scriptDirFor(root), wrapper.toString)
    for
      encrypted <- cache.ensure(encryptedPdf, "encrypted.pdf")
      _ = assertEquals(encrypted.left.toOption.map(_.code), Some("PDF_ENCRYPTED"))
      _ = assert(
        encrypted.left.toOption.exists(_.message.toLowerCase.contains("password")),
        s"readable failure expected: $encrypted"
      )
      entriesAfterFailure <- cache.entryCount
      _ = assertEquals(entriesAfterFailure, 0, "a failed parse must leave no entry")
      // Not cached as a negative verdict: the next ask tries again.
      again <- cache.ensure(encryptedPdf, "encrypted.pdf")
      _ = assertEquals(again.left.toOption.map(_.code), Some("PDF_ENCRYPTED"))
      spawns = spawnCount(log)
      _ = assertEquals(spawns, 2, s"a failed parse must be retried, not remembered (spawns=$spawns)")
      // A missing file is a readable failure too, and never reaches the parser.
      missing <- cache.ensure(root / "nope.pdf", "nope.pdf")
      _ = assertEquals(missing.left.toOption.map(_.code), Some("PDF_NOT_FOUND"))
      spawnsAfterMissing = spawnCount(log)
      _ = assertEquals(spawnsAfterMissing, 2, "a missing file must not spawn the parser")
    yield ()
    end for
  }

  test("ask selects pages, cites page numbers, and never hands over the whole document") {
    assume(pythonReady, "python3 + pdfplumber/pypdf are required for the PDF fixtures")
    val root = freshRoot("budget")
    val cache = PdfCache.forDataRoot(root)
    val doc = simplePdf
    val many = PdfAsk.ask(cache, root, doc, "simple.pdf", "r2c2 table value")
    for
      json <- many.map(_.toOption.getOrElse(fail("ask failed")))
      citations = json.hcursor.downField("citations").as[List[String]].toOption.getOrElse(Nil)
      excerpts = json.hcursor.downField("excerpts").as[List[io.circe.Json]].toOption.getOrElse(Nil)
      _ = assertEquals(citations.length, excerpts.length)
      _ = assert(citations.nonEmpty, "the table page must be found by its cell text")
      _ = assert(citations.contains("p.2"), s"page two holds the table, got $citations")
      _ = assert(citations.length <= PdfAsk.MaxPagesPerAsk, s"page budget exceeded: $citations")
      context = json.hcursor.downField("context").as[String].toOption.getOrElse("")
      _ = assert(context.length <= PdfAsk.MaxCharsPerAsk + 2000, s"context too large: ${context.length} chars")
      _ = assert(context.contains("--- page 2 ---"), "the context must label each excerpt with its page number")
      _ = assert(context.contains("Cite page numbers"), "the context must tell the answer to cite pages")
      // A page with no term overlap is not cited (no padding, no whole-document dump).
      unmatched <- PdfAsk.ask(cache, root, doc, "simple.pdf", "zzzznotpresent")
      _ = assertEquals(
        unmatched.toOption.flatMap(_.hcursor.downField("citations").as[List[String]].toOption),
        Some(Nil)
      )
      // A PDF whose text cannot be read is a readable failure, never a blank answer.
      enc <- PdfAsk.ask(cache, root, encryptedPdf, "encrypted.pdf", "anything")
      _ = assertEquals(enc.left.toOption.map(_.code), Some("PDF_ENCRYPTED"))
    yield ()
    end for
  }

  test("ask reads the manifest and the index first, then opens ONLY the matching pages") {
    assume(pythonReady, "python3 + pdfplumber/pypdf are required for the PDF fixtures")
    val root = freshRoot("ondemand")
    val cacheRoot = PdfCache.rootFor(root)
    val cache = PdfCache.forDataRoot(root)
    val doc = simplePdf
    for
      before <- IO.delay(PdfCache.pageReadsFor(cacheRoot))
      first <- PdfAsk.ask(cache, root, doc, "simple.pdf", "r2c2")
      json = first.toOption.getOrElse(fail(s"ask failed: $first"))
      after <- IO.delay(PdfCache.pageReadsFor(cacheRoot))
      reads = after - before
      citations = json.hcursor.downField("citations").as[List[String]].toOption.getOrElse(Nil)
      ledger = json.hcursor.downField("page_reads")
      matched = ledger.downField("matched_pages").as[Int].toOption
      opened = ledger.downField("pages_opened").as[Int].toOption
      total = ledger.downField("total_pages").as[Int].toOption
      wholeDoc = ledger.downField("whole_document_read").as[Boolean].toOption
      indexUsed = ledger.downField("index_used").as[Boolean].toOption
      // The fixture is 3 pages and the question names a cell of page 2 only.
      // RED (the previous ask): every page body was read to rank pages ⇒ 3.
      _ = assertEquals(reads, 1L, s"only the matching page may be opened; $reads page file(s) were read")
      _ = assertEquals(matched, Some(1), s"the index must resolve the question to exactly one page")
      _ = assertEquals(opened, Some(1))
      _ = assertEquals(total, Some(3))
      _ = assertEquals(wholeDoc, Some(false))
      _ = assertEquals(indexUsed, Some(true))
      _ = assertEquals(citations, List("p.2"), "the cited page carries the matched term")
      // A question that matches nothing opens nothing at all.
      before2 <- IO.delay(PdfCache.pageReadsFor(cacheRoot))
      none <- PdfAsk.ask(cache, root, doc, "simple.pdf", "zzzznotpresent")
      json2 = none.toOption.getOrElse(fail("ask failed"))
      after2 <- IO.delay(PdfCache.pageReadsFor(cacheRoot))
      _ = assertEquals(after2 - before2, 0L, "a question with no term overlap must open no page")
      _ = assertEquals(json2.hcursor.downField("citations").as[List[String]].toOption, Some(Nil))
    yield ()
    end for
  }

  test("the parser script and the JVM agree on the Markdown shape version") {
    val text =
      Option(getClass.getClassLoader.getResourceAsStream(PdfParser.ScriptResource))
        .map(s =>
          try new String(s.readAllBytes(), StandardCharsets.UTF_8)
          finally s.close()
        )
        .getOrElse(fail(s"${PdfParser.ScriptResource} must be on the classpath"))
    val declared = """(?m)^MARKDOWN_VERSION\s*=\s*(\d+)\s*$""".r.findFirstMatchIn(text).map(_.group(1).toInt)
    assertEquals(declared, Some(PdfParser.MarkdownVersion))
  }

  test("an unreadable meta.json is a miss with a reason, never an empty document") {
    val root = freshRoot("corrupt")
    val sha = "d" * 64
    val cache = PdfCache.forDataRoot(root)
    os.makeDir.all(cache.entryDir(sha))
    os.write.over(cache.metaPath(sha), "{ not json")
    for
      m <- cache.lookup(sha)
      _ = assertEquals(m, None, "a corrupt entry must not be served as an empty document")
    yield ()
  }
end PdfFeatureSpec
