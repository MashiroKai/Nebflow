_file_size() { stat -f %z "$1" 2>/dev/null || stat -c %s "$1" 2>/dev/null || echo 0; }

# TTY download with the brand progress bar: curl runs in the background
# writing to the target file; we poll its size and redraw the bar. Total
# size comes from a HEAD probe (content-length); unreachable -> spinner mode.
_download_progress() {  # <url> <target> <label> -> curl exit code
    local _url="$1" _target="$2" _label="$3"
    local _total
    _total=$(curl -fsSI --connect-timeout 5 --max-time 10 "$_url" 2>/dev/null \
        | tr -d '\r' | awk 'tolower($1)=="content-length:"{n=$2} END{if(n!="") printf "%d", n}')
    [ -z "$_total" ] && _total=-1
    curl -fsSL --connect-timeout 10 --max-time 120 "$_url" -o "$_target" 2>/dev/null &
    local _pid=$! _spin=0 _last=0 _now=0 _spd=-1
    while kill -0 "$_pid" 2>/dev/null; do
        _now=$(_file_size "$_target")
        _spd=$(( (_now - _last) * 2 ))   # 0.5s poll interval
        _last=$_now
        progress_render "$_now" "$_total" "$_label" "$_spd" "$_spin"
        _spin=$((_spin+1))
        sleep 0.5 2>/dev/null || sleep 1
    done
    local _rc=0
    wait "$_pid" || _rc=$?
    _now=$(_file_size "$_target")
    progress_render "$_now" "$_total" "$_label" -1 "$_spin"
    printf '\n'
    return "$_rc"
}

_download() {
    local url="$1" target="$2" label="${3:-}"
    if _progress_ok; then
        _download_progress "$url" "$target" "${label:-$(basename "$target")}"
    else
        # non-TTY (curl|bash pipe) / dumb terminal: plain one-line log
        [ -n "$label" ] && log_i "Downloading ${label}..."
        if command -v curl &> /dev/null; then
            curl -fsSL --connect-timeout 10 --max-time 120 "${url}" -o "${target}"
        elif command -v wget &> /dev/null; then
            wget --connect-timeout=10 --timeout=120 -q "${url}" -O "${target}"
        else
            log_err "curl or wget is required."
            exit $ERR_CURL
        fi
    fi
}

# ---- checksum machinery (deps/ integrity, batch 2) ------------------------

CHECKSUMS_LOADED=""
CHECKSUMS_CONTENT=""

sha256_of() {  # <file> -> hash (or empty when no tool available)
    if command -v shasum > /dev/null 2>&1; then
        shasum -a 256 "$1" 2>/dev/null | awk '{print $1}'
    elif command -v sha256sum > /dev/null 2>&1; then
        sha256sum "$1" 2>/dev/null | awk '{print $1}'
    fi
}

fetch_checksum_for() {  # <filename> -> expected sha256 (or empty = unknown)
    if [ -z "$CHECKSUMS_LOADED" ]; then
        CHECKSUMS_CONTENT=$(curl -fsSL --connect-timeout 5 --max-time 15 \
            "${COS_DEPS_BASE}/checksums.txt" 2>/dev/null || true)
        CHECKSUMS_LOADED=1
        [ -n "$CHECKSUMS_CONTENT" ] && log_v "Loaded deps/checksums.txt from COS." \
            || log_v "deps/checksums.txt unreachable - checksum verification degraded."
    fi
    [ -n "$CHECKSUMS_CONTENT" ] || return 0
    awk -v f="$1" '$2 == f { print $1; exit }' <<< "$CHECKSUMS_CONTENT"
}

expected_checksum_hint() {  # <filename> -> "sha256: <hash>" line (or empty)
    local h
    h=$(fetch_checksum_for "$1")
    [ -n "$h" ] && echo "       sha256: ${h}"
}

# Multi-source download with checksum verification. Every candidate source
# (COS first by convention) is verified against deps/checksums.txt when the
# manifest is reachable; a mismatched source is discarded and the next one
# is tried. Unknown checksum (manifest unreachable) degrades to accept.
#   download_file <target> <filename-in-manifest> <label> <url1> [url2] ...
download_file() {
    local target="$1" name="$2" label="$3"; shift 3
    local url verdict
    for url in "$@"; do
        log_v "Trying source: ${url}"
        if _download "$url" "$target" "$label"; then
            verdict=$(verify_checksum "$target" "$name") || true
            case "$verdict" in
                ok)      return 0 ;;
                bad)     rm -f "$target"; continue ;;
                unknown) return 0 ;;
            esac
        else
            rm -f "$target"
        fi
    done
    return 1
}

verify_checksum() {  # <file> <filename-in-manifest> -> echoes ok|bad|unknown
    local file="$1" name="$2" expected actual
    expected=$(fetch_checksum_for "$name")
    if [ -z "$expected" ]; then
        echo "unknown"
        return 0
    fi
    actual=$(sha256_of "$file")
    if [ -z "$actual" ]; then
        echo "unknown"   # no sha256 tool available - degrade, don't misjudge
        return 0
    fi
    if [ "$actual" = "$expected" ]; then
        echo "ok"
        return 0
    fi
    echo "bad"
    return 0
}

download_jar() {
    stage_hdr 3 "Downloading ${PRODUCT_NAME} v${VERSION}..."
    # Version-dependent names are computed here (VERSION resolves in
    # resolve_version, before this stage runs).
    JAR_NAME="${LOWER_NAME}-assembly-${VERSION}.jar"
    COS_URL="${COS_BASE_CN}/${JAR_NAME}"
    local target="${INSTALL_DIR}/${JAR_NAME}"
    mkdir -p "${INSTALL_DIR}"

    # Idempotency: same version already in place -> skip (no re-download)
    if [ -f "${target}" ]; then
        log_ok "Already up-to-date (v${VERSION})."
        return 0
    fi

    # Remove old JAR files (keep user data untouched)
    local old_jars
    old_jars=$(ls "${INSTALL_DIR}"/${LOWER_NAME}-assembly-*.jar "${INSTALL_DIR}"/nebflow-assembly-*.jar 2>/dev/null || true)
    if [ -n "$old_jars" ]; then
        log_i "Removing old version(s)..."
        rm -f "${INSTALL_DIR}"/${LOWER_NAME}-assembly-*.jar "${INSTALL_DIR}"/nebflow-assembly-*.jar
    fi

    # #29: 仓库 private 后 GitHub Releases 未认证 404——COS 单一源
    if _download "${COS_URL}" "${target}" "${JAR_NAME}"; then
        log_ok "Downloaded ${JAR_NAME} from COS."
        return 0
    fi
    log_err "Download failed from COS. Check ${COS_URL}"
    exit $ERR_JAR
}

