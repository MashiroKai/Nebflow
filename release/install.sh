#!/bin/bash
set -e

# Nebflow cross-platform installer (macOS / Linux) — script v2
# ---------------------------------------------------------------
# SCRIPT_VERSION : installer version (written into the local install
#                  manifest for `nebflow update` and diagnostics).
# Pipeline       : [1/6] env detect -> [2/6] deps (curl/JDK/rg/voice) ->
#                  [3/6] jar -> [4/6] wrapper+PATH -> [5/6] config ->
#                  [6/6] done.
# Idempotent     : safe to re-run; installed/satisfied deps are detected
#                  and skipped.
# Flags          : --beta | --channel=beta | --cn | --global | --verbose
#                  (curl|bash pipe: env CHANNEL=beta / REGION=cn /
#                  NEBFLOW_VERBOSE=1)
# Exit codes     : 0 ok | 10 version resolve | 11 java install |
#                  12 jar download | 13 no curl/wget
# ---------------------------------------------------------------

# -- Brand values (L2 rebrand): rendered from repo-root brand.conf at -------
# -- release time (scripts/render-brand.sh); do not edit by hand. -----------
# The runtime dual-reads legacy names (L3), so rendering NEW values here
# keeps existing user data working - old dirs/env/config fall back.
PRODUCT_NAME=Nebflow
LOWER_NAME=nebflow
COS_BUCKET=nebflow-releases-1411212853
HOME_DIR=.nebflow
CONFIG_FILE=nebflow.json
WRAPPER_NAME=nebflow
COS_BASE_CN="https://${COS_BUCKET}.cos.ap-nanjing.myqcloud.com"
# Batch 2 (v2): all third-party deps mirrored on COS under the deps/ prefix
# (single primary source for every region; upstream sources demoted to
# fallback). Integrity via deps/checksums.txt (sha256, generated by
# scripts/upload-deps.sh at upload time).
COS_DEPS_BASE="${COS_BASE_CN}/deps"
# 仓库已转 private（#29，2026-09-01）：GitHub Releases 未认证下载 404——
# Nebflow jar 下载/版本解析统一走 COS（单一源）。第三方依赖
# （Homebrew/ripgrep/HuggingFace 模型/favicon 连通性测试）
# 与仓库 private 无关，仍走各自公共源。

SCRIPT_VERSION="2.0.0"
RG_VERSION="14.1.1"
JDK_MAJOR_REQUIRED=17   # runtime floor; fresh installs target OpenJDK 21
ERR_VERSION=10
ERR_JAVA=11
ERR_JAR=12
ERR_CURL=13

# -- unified log helpers ----------------------------------------------------
VERBOSE="${NEBFLOW_VERBOSE:-0}"
log_i()    { echo "[i] $*"; }
log_ok()   { echo "[ok] $*"; }
log_warn() { echo "[warn] $*"; }
log_err()  { echo "[err] $*" >&2; }
log_v()    { [ "$VERBOSE" = "1" ] && echo "[v] $*" || true; }
stage_hdr(){ echo ""; echo "==> [$1/6] $2"; }

# Parse flags
CHANNEL="stable"
for arg in "$@"; do
    case "$arg" in
        --beta|--channel=beta) CHANNEL="beta" ;;
        --cn) REGION="cn" ;;
        --global) REGION="global" ;;
        --verbose) VERBOSE=1 ;;
    esac
done

# Resolve version — COS version file (single source; GH API private 后不可用)
resolve_version() {
    if [ "$CHANNEL" = "beta" ]; then
        log_i "Resolving latest beta version..."
        if [ -z "$VERSION" ]; then
            BETA_TAG=$(curl -fsSL --connect-timeout 5 --max-time 10 \
                "${COS_BASE_CN}/latest-beta-version.txt" 2>/dev/null || true)
            if [ -z "$BETA_TAG" ]; then
                log_err "Could not find a beta release (COS version file unreachable)."
                log_err "Check ${COS_BASE_CN}/latest-beta-version.txt"
                exit $ERR_VERSION
            fi
            VERSION="$BETA_TAG"
        fi
    else
        log_i "Resolving latest stable version..."
        if [ -z "$VERSION" ]; then
            LATEST_VERSION=$(curl -fsSL --connect-timeout 5 --max-time 10 \
                "${COS_BASE_CN}/latest-version.txt" 2>/dev/null || true)
            if [ -z "$LATEST_VERSION" ]; then
                log_err "Could not resolve latest version (COS version file unreachable)."
                log_err "Check ${COS_BASE_CN}/latest-version.txt"
                exit $ERR_VERSION
            fi
            VERSION="$LATEST_VERSION"
        fi
    fi
    log_v "Resolved VERSION=${VERSION} (channel=${CHANNEL})"
}

INSTALL_DIR="${INSTALL_DIR:-${HOME}/${HOME_DIR}/bin}"

# >>> BRAND-UI-BEGIN (batch 4 redesign: pixel logo + progress bar) >>>
# Brand banner: the Nebflow 7x7 pixel logo rendered as terminal color
# blocks. The matrix was sampled OFFLINE from the brand assets
# (docs/Nebflow/assets/logo/{dark,bright}.png, 224x224 = a 7x7 grid of 32px
# cells, cell-center NEAREST sampling - the same pixelated look as the web
# UI's image-rendering: pixelated) and embedded here as constant data: zero
# image files, zero python, zero network at runtime. Full untrimmed 7x7
# matrix (author ruling 2026-09-06: no 5x6 cropping - keeps the source
# aspect); G = brand green #07C160, W = white (dark terminals) or
# black (light terminals). No ASCII-art/figlet wordmark: the logo blocks
# carry the brand, the wordmark is plain lowercase text.
#
# Color degrade chain: truecolor (3) -> xterm-256 (2) -> 8-color (1) ->
# mono # mask (0), every level keeps the shape intact. Width discipline
# (author ruling 2026-09-06, revised same-day): ONE pixel = TWO character
# cells at every level - a terminal glyph is ~2x taller than wide, so each
# pixel spans 2 columns and the logo keeps its source aspect. Mono renders
# "##" per pixel, color levels render a 2-column background block, empty
# pixels are 2 plain spaces; adjacent solid pixels touch with no gap
# (e.g. mask row "GG.WWW." -> "####  ######  ", 14 columns per logo row).
#   guards: NO_COLOR / CI / non-TTY / TERM=dumb -> mono (plain text)
#   theme : NEBFLOW_BANNER_THEME=dark|light overrides; else COLORFGBG's
#           background field (>=7 means a light background); default dark
#   level : NEBFLOW_UI_LEVEL=0..3 forces a level (preview/testing)

BANNER_MASK=(
    "......."
    "GG.WWW."
    "GG.WWW."
    "..W..W."
    "..W..W."
    "..W..W."
    "......."
)

_ui_level=0
_ui_theme="dark"
_ui_utf8=0
case "${LC_ALL:-${LC_CTYPE:-${LANG:-}}}" in
    *UTF-8*|*utf8*|*utf-8*) _ui_utf8=1 ;;
esac

ui_detect() {
    case "${NEBFLOW_UI_LEVEL:-}" in
        0|1|2|3) _ui_level="${NEBFLOW_UI_LEVEL}" ;;
        *)
            _ui_level=0
            if [ -t 1 ] && [ -z "${NO_COLOR:-}" ] && [ -z "${CI:-}" ] && [ "${TERM:-dumb}" != "dumb" ]; then
                case "${COLORTERM:-}" in
                    truecolor|24bit) _ui_level=3 ;;
                    *) case "${TERM:-}" in
                           *256color*) _ui_level=2 ;;
                           *)         _ui_level=1 ;;
                       esac ;;
                esac
            fi
            ;;
    esac
    case "${NEBFLOW_BANNER_THEME:-}" in
        dark|light) _ui_theme="${NEBFLOW_BANNER_THEME}" ;;
        *)
            _ui_theme="dark"
            if [ -n "${COLORFGBG:-}" ]; then
                local _bg="${COLORFGBG##*;}"
                case "$_bg" in
                    ''|*[!0-9]*) : ;;
                    *) [ "$_bg" -ge 7 ] 2>/dev/null && _ui_theme="light" ;;
                esac
            fi
            ;;
    esac
}

# -- low-level painters -------------------------------------------------------
# One logo pixel = TWO character cells at every color level (author ruling
# 2026-09-06, revised): "##" in mono, a 2-column bg block in color levels;
# transparent pixels are two plain spaces. Adjacent solid pixels connect
# with no separator.
_px() {  # <G|W|.>
    case "$1" in
        .) printf '  '; return 0 ;;
    esac
    case "$_ui_level" in
        3)
            if [ "$1" = "G" ]; then printf '\033[48;2;7;193;96m  \033[0m'
            elif [ "$_ui_theme" = "dark" ]; then printf '\033[48;2;255;255;255m  \033[0m'
            else printf '\033[48;2;0;0;0m  \033[0m'; fi
            ;;
        2)  # nearest xterm-256: #07C160 -> 35 (#00af5f); white 231; black 16
            if [ "$1" = "G" ]; then printf '\033[48;5;35m  \033[0m'
            elif [ "$_ui_theme" = "dark" ]; then printf '\033[48;5;231m  \033[0m'
            else printf '\033[48;5;16m  \033[0m'; fi
            ;;
        1)
            if [ "$1" = "G" ]; then printf '\033[42m  \033[0m'
            elif [ "$_ui_theme" = "dark" ]; then printf '\033[47m  \033[0m'
            else printf '\033[40m  \033[0m'; fi
            ;;
        *)  printf '##' ;;
    esac
}

_fg_green() {
    case "$_ui_level" in
        3) printf '\033[1;38;2;7;193;96m' ;;
        2) printf '\033[1;38;5;35m' ;;
        1) printf '\033[1;32m' ;;
    esac
}
_dim() { [ "$_ui_level" -ge 1 ] && printf '\033[2m' || true; }
_rst() { [ "$_ui_level" -ge 1 ] && printf '\033[0m' || true; }

print_banner() {
    ui_detect
    printf '\n'
    local _i _j _row
    for _i in 0 1 2 3 4 5 6; do
        _row="${BANNER_MASK[$_i]}"
        printf '  '
        for ((_j=0; _j<${#_row}; _j++)); do _px "${_row:$_j:1}"; done
        case "$_i" in
            2) printf '  '; _fg_green; printf '%s' "${LOWER_NAME}"; _rst ;;
            3) printf '  '; _dim; printf 'v%s installer (%s)' "${VERSION:-dev}" "${CHANNEL}"; _rst ;;
        esac
        printf '\n'
    done
    printf '\n'
}

# -- download progress --------------------------------------------------------
# Clean single-line bar in brand green: percentage only when content-length
# is known (unknown length -> spinner + byte count, never a fake %), current
# file label, size/speed. In-place \r redraw, COLUMNS-adaptive. Non-TTY
# (curl|bash pipe) / TERM=dumb: no control output at all, plain log lines.

_progress_ok() {
    [ -t 1 ] && [ "${TERM:-dumb}" != "dumb" ] && command -v curl > /dev/null 2>&1
}

_fmt_bytes() {  # <bytes> -> "12.3M" / "640K" / "512B"
    awk -v b="${1:-0}" 'BEGIN{
        if (b >= 1048576) printf "%.1fM", b/1048576;
        else if (b >= 1024) printf "%.0fK", b/1024;
        else printf "%dB", b;
    }'
}

_bar() {  # <done> <total|-1> <width> -> bar body (no newline)
    local _done=$1 _total=$2 _w=$3
    local _e=0 _filled=0 _frac=0 _i _out=""
    if [ "$_total" -gt 0 ] 2>/dev/null; then
        _e=$(( _done * _w * 8 / _total ))
        [ "$_e" -gt $((_w*8)) ] && _e=$((_w*8))
        _filled=$((_e/8)); _frac=$((_e%8))
    fi
    local _g="" _r="" _d=""
    case "$_ui_level" in
        3) _g=$'\033[38;2;7;193;96m' ;;
        2) _g=$'\033[38;5;35m' ;;
        1) _g=$'\033[32m' ;;
    esac
    if [ -n "$_g" ]; then _r=$'\033[0m'; _d=$'\033[2m'; fi
    _out="$_g"
    if [ "$_ui_utf8" = 1 ]; then
        # eighth-block partials give sub-cell precision
        local _parts=("" "▏" "▎" "▍" "▌" "▋" "▊" "▉")
        for ((_i=0; _i<_filled; _i++)); do _out="${_out}█"; done
        if [ "$_frac" -gt 0 ]; then _out="${_out}${_parts[$_frac]}"; _filled=$((_filled+1)); fi
        _out="${_out}${_r}${_d}"
        for ((_i=_filled; _i<_w; _i++)); do _out="${_out}░"; done
    else
        for ((_i=0; _i<_filled; _i++)); do _out="${_out}#"; done
        if [ "$_frac" -gt 0 ]; then _out="${_out}>"; _filled=$((_filled+1)); fi
        _out="${_out}${_r}"
        for ((_i=_filled; _i<_w; _i++)); do _out="${_out}-"; done
    fi
    _out="${_out}${_r}"
    printf '%s' "$_out"
}

# Compose one full progress line (colors included). Pure function of its
# arguments - also driven by scripts/preview-brand-ui.sh for static frames.
_progress_line() {  # <done> <total|-1> <label> <speed_Bps|-1> <spin_idx>
    local _done=$1 _total=$2 _label=$3 _spd=$4 _spin=$5
    local _cols=${COLUMNS:-80}
    local _info=" $(_fmt_bytes "$_done")"
    [ "$_total" -gt 0 ] 2>/dev/null && _info="${_info}/$(_fmt_bytes "$_total")"
    [ "$_spd" -ge 0 ] 2>/dev/null && _info="${_info}  $(_fmt_bytes "$_spd")/s"
    local _pct
    if [ "$_total" -gt 0 ] 2>/dev/null; then
        _pct=$(awk -v d="$_done" -v t="$_total" 'BEGIN{p=int(d*100/t); printf "%3d%%", (p>100?100:p)}')
    else
        local _s='|/-\'
        _pct="  ${_s:$((_spin % 4)):1} "
    fi
    local _w=$(( _cols - ${#_label} - ${#_info} - 16 ))
    [ "$_w" -lt 10 ] && _w=10
    [ "$_w" -gt 48 ] && _w=48
    printf '  %s %s%s  %s' "$_pct" "$(_bar "$_done" "$_total" "$_w")" "$_info" "$_label"
}

progress_render() {  # <done> <total|-1> <label> <speed_Bps|-1> <spin_idx>
    _progress_ok || return 0
    printf '\r\033[K%s' "$(_progress_line "$@")"
}
