    } catch { $dlOk = $false }
    if ($dlOk) {
        Write-Ok "Voice model installed."
    } else {
        Write-Warn2 "Download failed (voice will use CDN on first use)."
    }
}

# --- [6/7] Create wrapper scripts ---
